// Writes supabase/seed/products.sql from the storefront catalogue
// (src/lib/data/products.json), so the database's product list matches the
// site, field for field. Run with `npm run db:products`, then run the file in
// the Supabase SQL editor (or psql) — on a test project first, after a backup.
//
// Safe to run again, and safe for customer data:
// - rows are matched by slug and updated in place: a product's id never
//   changes, so favourites and order lines keep pointing at it; nothing is
//   deleted
// - a row an admin has edited (updated_by set) is left exactly as it is
// - watches no longer in products.json are retired (is_active = false), unless
//   an admin has edited them
// Needs Node 22.18+ (it reads the TypeScript catalogue helpers directly).
import { readFileSync, writeFileSync } from "node:fs";

if (!process.features?.typescript) {
  console.error("Node 22.18 veya üstü gerekli (TypeScript dosyalarını doğrudan okuyabilmek için).");
  process.exit(1);
}
const { productToRow } = await import("../src/lib/catalog/rows.ts");
const { BRANDS } = await import("../src/lib/data/brands.ts");

const root = new URL("..", import.meta.url);
const products = JSON.parse(readFileSync(new URL("src/lib/data/products.json", root), "utf8"));

const brandName = (slug) => {
  const brand = BRANDS.find((b) => b.slug === slug);
  if (!brand) throw new Error(`Bilinmeyen marka: ${slug}`);
  return brand.name;
};

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const textArray = (list) => (list.length ? `array[${list.map(q).join(", ")}]` : "'{}'::text[]");

const COLUMNS = [
  "slug", "name", "brand", "brand_slug", "model", "reference", "description", "price", "currency", "image",
  "images", "front", "specs", "condition", "availability", "full_set", "collections", "featured", "added_at",
  "tone", "position", "stock",
];

const values = (r) =>
  [
    q(r.slug),
    q(r.name),
    q(r.brand),
    q(r.brand_slug),
    q(r.model),
    q(r.reference),
    q(r.description),
    r.price === null ? "null" : r.price.toFixed(2),
    q(r.currency),
    q(r.image),
    textArray(r.images),
    q(r.front),
    `${q(JSON.stringify(r.specs))}::jsonb`,
    q(r.condition),
    q(r.availability),
    r.full_set,
    textArray(r.collections),
    r.featured,
    `${q(r.added_at)}::date`,
    q(r.tone),
    r.position,
    r.stock,
  ].join(", ");

const rows = products.map((p, i) => productToRow(p, i, brandName(p.brand)));
const slugs = new Set();
for (const r of rows) {
  if (slugs.has(r.slug)) throw new Error(`Aynı slug iki kez: ${r.slug}`);
  slugs.add(r.slug);
}

const sql = `-- Generated by scripts/products-seed.mjs from src/lib/data/products.json. Do not edit by hand.
-- Needs supabase/migrations/20261026120000_admin_catalog.sql. Matches rows by slug:
-- ids never change and nothing is deleted; rows an admin has edited are left alone.
insert into public.products (${COLUMNS.join(", ")})
values
${rows.map((r) => `  (${values(r)})`).join(",\n")}
on conflict (slug) do update set
${COLUMNS.filter((c) => c !== "slug")
  .map((c) => `  ${c} = excluded.${c},`)
  .join("\n")}
  is_active = true
where public.products.updated_by is null;

-- Watches no longer in the catalogue stay for old orders and favourites but leave the shop.
update public.products set is_active = false
 where updated_by is null
   and slug not in (${rows.map((r) => q(r.slug)).join(", ")});
`;

writeFileSync(new URL("supabase/seed/products.sql", root), sql);
console.log(`supabase/seed/products.sql: ${rows.length} products`);
